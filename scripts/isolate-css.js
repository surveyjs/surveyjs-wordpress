const fs = require("fs");
const path = require("path");

const TRUNK = path.join(__dirname, "../src/trunk");
const CONTAINER = ".wp-sjs-survey";
// Twenty Twenty-One's ".has-background button:not(:hover):not(:active):not(.has-text-color)" is (0,5,1), the strongest
// theme rule found on form elements; the scope must outweigh it on its own because the reset adds nothing to it.
const SCOPE_WEIGHT = 6;
const SCOPE = CONTAINER.repeat(SCOPE_WEIGHT);
// .wp-sjs-adaptive sits on the container on the front end and on a child of it in the editor preview.
const OWN_ROOTS =/^(\.wp-sjs-survey|\.wp-sjs-adaptive)(?![\w-])/;
const PAGE_ROOTS = /^(:root|:host|html|body)(?![\w-])/;
// Content that the form author writes (HTML questions, Markdown in titles) keeps the site's look, and SVG icons
// keep their presentation attributes, which `all: revert` would wipe.
const KEEP = "svg, svg *, .sd-html *, .sv-string-viewer *";
const RESET = [
    `${SCOPE} :where(:not(${KEEP}, img, video, iframe, canvas))`,
    `${SCOPE} :where(:not(${KEEP}))::before`,
    `${SCOPE} :where(:not(${KEEP}))::after`,
    `${SCOPE} :where(:not(${KEEP}))::placeholder`
].join(",") + "{all:revert}";

const OUTPUTS = [
    { from: "libs/library/survey-core.min.css", to: "isolated/survey-core.min.css", scope: (selector) => `${SCOPE} ${selector}`, prepend: RESET },
    { from: "themes/wordpress.css", to: "isolated/wordpress.css", scope: (selector) => (OWN_ROOTS.test(selector) ? `:is(${SCOPE},${SCOPE} *)${selector}` : null) }
];

function skipString(text, index) {
    const quote = text[index];
    let i = index + 1;
    while (i < text.length && text[i] !== quote) i += text[i] === "\\" ? 2 : 1;
    return i + 1;
}

function blockEnd(text, open) {
    let depth = 0;
    for (let i = open; i < text.length;) {
        const ch = text[i];
        if (ch === "/" && text[i + 1] === "*") { i = text.indexOf("*/", i + 2) + 2; continue; }
        if (ch === '"' || ch === "'") { i = skipString(text, i); continue; }
        if (ch === "{") depth++;
        else if (ch === "}" && --depth === 0) return i;
        i++;
    }
    throw new Error(`Unclosed block at ${open}`);
}

function splitTop(text, separator) {
    const parts = [];
    let depth = 0;
    let start = 0;
    for (let i = 0; i < text.length;) {
        const ch = text[i];
        if (ch === '"' || ch === "'") { i = skipString(text, i); continue; }
        if (ch === "(" || ch === "[") depth++;
        else if (ch === ")" || ch === "]") depth--;
        else if (ch === separator && depth === 0) { parts.push(text.slice(start, i)); start = i + 1; }
        i++;
    }
    parts.push(text.slice(start));
    return parts.map((part) => part.trim()).filter(Boolean);
}

function scopeRule(selectorText, body, scope) {
    const declarations = splitTop(body.replace(/\/\*[\s\S]*?\*\//g, ""), ";");
    const variables = declarations.filter((declaration) => declaration.startsWith("--"));
    const properties = declarations.filter((declaration) => !declaration.startsWith("--"));
    const selectors = splitTop(selectorText, ",");
    const scoped = selectors.map((selector) => (PAGE_ROOTS.test(selector) ? null : scope(selector)));
    if (!properties.length || scoped.every((selector) => selector === null)) return `${selectorText}{${body}}`;
    const kept = selectors.filter((selector, index) => scoped[index] === null);
    let css = variables.length ? `${selectors.join(",")}{${variables.join(";")}}` : "";
    if (kept.length) css += `${kept.join(",")}{${properties.join(";")}}`;
    css += `${scoped.filter(Boolean).join(",")}{${properties.join(";")}}`;
    return css;
}

function transform(text, scope) {
    let out = "";
    let i = 0;
    while (i < text.length) {
        const ch = text[i];
        if (ch === "/" && text[i + 1] === "*") { i = text.indexOf("*/", i + 2) + 2; continue; }
        if (/\s/.test(ch)) { i++; continue; }
        let j = i;
        while (j < text.length && text[j] !== "{" && text[j] !== ";") j = text[j] === '"' || text[j] === "'" ? skipString(text, j) : j + 1;
        const head = text.slice(i, j).trim();
        if (text[j] === ";") { out += `${head};`; i = j + 1; continue; }
        const end = blockEnd(text, j);
        const body = text.slice(j + 1, end);
        if (head.startsWith("@")) {
            out += /^@(media|supports|container|layer|-moz-document)\b/.test(head) ? `${head}{${transform(body, scope)}}` : `${head}{${body}}`;
        } else {
            out += scopeRule(head, body.trim(), scope);
        }
        i = end + 1;
    }
    return out;
}

const banner = "/* Generated by scripts/isolate-css.js, do not edit. */\n";
for (const output of OUTPUTS) {
    const source = fs.readFileSync(path.join(TRUNK, output.from), "utf8").replace(/^﻿/, "");
    const license = (/^\/\*![\s\S]*?\*\//.exec(source) || [""])[0];
    const css = (license ? license + "\n" : "") + banner + (output.prepend || "") + transform(source, output.scope);
    fs.mkdirSync(path.dirname(path.join(TRUNK, output.to)), { recursive: true });
    fs.writeFileSync(path.join(TRUNK, output.to), css);
    console.log(`${output.to}: ${css.length} bytes`);
}
