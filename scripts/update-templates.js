const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");

const REPOSITORY = "https://github.com/surveyjs/templates.git";
const root = path.join(__dirname, "..");
const target = path.join(root, "src", "trunk", "templates");

function git(args, cwd) {
  return execFileSync("git", args, { cwd, encoding: "utf8" }).trim();
}

function checkout() {
  if (process.argv[2]) return { dir: path.resolve(process.argv[2]), temporary: false };
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "surveyjs-templates-"));
  git(["clone", "--quiet", "--depth", "1", REPOSITORY, dir]);
  return { dir, temporary: true };
}

const THUMBNAIL = "thumbnail.webp";
const CATEGORIES = "categories.json";
const CATEGORIES_PHP = "categories.php";

function templateFiles(dir, relative = "") {
  return fs.readdirSync(path.join(dir, relative), { withFileTypes: true }).flatMap((entry) => {
    const file = path.join(relative, entry.name);
    if (entry.name.startsWith(".") || entry.name === "node_modules" || entry.name === "local") return [];
    if (entry.isDirectory()) return templateFiles(dir, file);
    return relative && (entry.name.endsWith(".json") || entry.name === THUMBNAIL) ? [file] : [];
  });
}

function categoryLabels(dir, files) {
  const file = path.join(dir, CATEGORIES);
  if (!fs.existsSync(file)) throw new Error(`${CATEGORIES} is missing in the templates repository root`);
  const labels = JSON.parse(fs.readFileSync(file, "utf8"));
  if (!labels || typeof labels !== "object" || Array.isArray(labels)) throw new Error(`${CATEGORIES} must map category folders to labels`);
  const used = [...new Set(files.map((file) => file.split(path.sep)[0]))].sort();
  const missing = used.filter((slug) => typeof labels[slug] !== "string" || !labels[slug].trim());
  if (missing.length) throw new Error(`${CATEGORIES} has no label for: ${missing.join(", ")}`);
  const invalid = used.filter((slug) => !/^[a-z0-9-]+$/.test(slug));
  if (invalid.length) throw new Error(`Category folders must be lowercase words joined by hyphens: ${invalid.join(", ")}`);
  return used.map((slug) => [slug, labels[slug].trim()]);
}

function phpString(value) {
  return `'${value.replace(/[\\']/g, "\\$&")}'`;
}

function categoriesPhp(labels) {
  const width = Math.max(...labels.map(([slug]) => phpString(slug).length));
  const rows = labels.map(([slug, label]) => `    ${phpString(slug).padEnd(width)} => __( ${phpString(label)}, 'surveyjs' ),`);
  return [
    "<?php",
    `// Generated by scripts/update-templates.js from ${CATEGORIES} in the templates repository. Literal __() calls let translate.wordpress.org pick up the labels.`,
    "if ( ! defined( 'ABSPATH' ) ) exit;",
    "",
    "return array(",
    ...rows,
    ");",
    "",
  ].join("\n");
}

const source = checkout();
try {
  const files = templateFiles(source.dir);
  for (const file of files) {
    const content = fs.readFileSync(path.join(source.dir, file));
    if (file.endsWith(".json")) JSON.parse(content.toString("utf8"));
    else if (content.toString("ascii", 0, 4) !== "RIFF" || content.toString("ascii", 8, 12) !== "WEBP") throw new Error(`${file} is not a WebP image`);
  }
  const labels = categoryLabels(source.dir, files);
  fs.rmSync(target, { recursive: true, force: true });
  for (const file of files) {
    fs.mkdirSync(path.dirname(path.join(target, file)), { recursive: true });
    fs.copyFileSync(path.join(source.dir, file), path.join(target, file));
  }
  fs.writeFileSync(path.join(target, CATEGORIES_PHP), categoriesPhp(labels));
  const commit = git(["rev-parse", "HEAD"], source.dir);
  fs.writeFileSync(path.join(target, "source.txt"), `${REPOSITORY} ${commit}\n`);
  console.log(`src/trunk/templates: ${files.length} files, ${labels.length} categories from ${commit}`);
} finally {
  if (source.temporary) fs.rmSync(source.dir, { recursive: true, force: true });
}
